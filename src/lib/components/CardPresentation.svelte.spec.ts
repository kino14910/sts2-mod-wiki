import { afterEach, describe, expect, it, vi } from 'vitest'
import { page } from 'vitest/browser'
import { render } from 'vitest-browser-svelte'
import { CARDS, CHARACTER_ASSETS } from '#lib/data/mods'
import { cardCharacterOptions } from '#lib/data/characters'
import { getLocale, setLocale } from '#lib/paraglide/runtime'
import CharacterFilter from './CharacterFilter.svelte'
import CardThumb from './CardThumb.svelte'

// Keep this focused on the actual catalog and DOM resource selection; image optimization
// and serving the imported bytes are exercised by the production E2E test.
vi.mock('#lib/data/card-images', () => ({ cardUiImage: () => undefined }))

const initialLocale = getLocale()
afterEach(() => { setLocale(initialLocale, { reload: false }) })

describe('imported card presentation', () => {
	it('shows a labelled Noble Phantasm character button in both languages and toggles it', async () => {
		setLocale('zhs', { reload: false })
		const onchange = vi.fn()
		const view = await render(CharacterFilter, { options: cardCharacterOptions(), sortable: false, onchange })
		// The button's translated accessible name is generated by Paraglide.
		const noble = document.querySelector<HTMLButtonElement>('button[title="宝具"]')!
		expect(noble).not.toBeNull()
		expect(noble.querySelector('img')?.getAttribute('src')).toBe(CHARACTER_ASSETS.noble.char)
		noble.click()
		await expect.element(page.getByRole('button', { name: noble.getAttribute('aria-label')!, exact: true })).toHaveAttribute('aria-pressed', 'true')
		expect(onchange).toHaveBeenCalledTimes(1)
		noble.click()
		await expect.element(page.getByRole('button', { name: noble.getAttribute('aria-label')!, exact: true })).toHaveAttribute('aria-pressed', 'false')
		setLocale('eng', { reload: false })
		await view.rerender({ options: cardCharacterOptions() })
		expect(document.querySelector('button[title="Noble Phantasm"]')).not.toBeNull()
	});

	it('selects the type-specific imported frames and reacts when a card changes pool or type', async () => {
		const card = CARDS.find((card) => card.mod === 'fgo' && card.id === 'Strike')!
		const view = await render(CardThumb, { card, showText: false })
		for (const type of ['attack', 'skill', 'power'] as const) {
			await view.rerender({ card: { ...card, type } })
			expect(document.querySelector('.card-frame')?.getAttribute('src')).toBe(CHARACTER_ASSETS.fgo.cardFrame?.[type])
		}
		// {} is a deliberate no-frame setting, even for a non-full-art card.
		await view.rerender({ card: { ...card, pool: ['noble'], color: 'noble', fullArt: false } })
		expect(document.querySelector('.card-frame')).toBeNull()
		expect(document.querySelector<HTMLElement>('.card-thumb')?.style.getPropertyValue('--cost-image'))
			.toContain(CHARACTER_ASSETS.noble.cardEnergy)
		const vanilla = CARDS.find((card) => card.mod === 'sts2' && card.id === 'Bash')!
		await view.rerender({ card: vanilla })
		expect(document.querySelector('.card-frame')?.getAttribute('src')).toBe('/images/card_frames/attack.png')
	});
})
