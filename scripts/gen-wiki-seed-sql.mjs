import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)))
const readJson = (file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'))
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`

const relicWiki = readJson('src/lib/data/relic-wiki.json')
const powerWiki = readJson('src/lib/data/power-wiki.json')
const summary = 'Initial import from mod provided wiki data'

const documents = [
	...Object.entries(relicWiki).map(([id, page]) => ({
		ref: { type: 'relic', id },
		source: `src/lib/data/relic-wiki.json#${id}`,
		document: { kind: 'relic', page }
	})),
	...Object.entries(powerWiki).map(([id, page]) => ({
		ref: { type: 'power', id },
		source: `src/lib/data/power-wiki.json#${id}`,
		document: { kind: 'power', page }
	}))
]

const lines = [
	'-- Generated by scripts/gen-wiki-seed-sql.mjs. Do not edit by hand.',
	'-- Legacy structured wiki pages are seeded once as mod_seed revisions.',
	''
]

for (const { ref, source, document } of documents) {
	const key = `${ref.type}:${ref.id}`
	const pageId = `seed:page:${key}`
	const sectionId = `seed:section:${key}:document`
	const revisionId = `seed:revision:${key}:document:1`

	lines.push(
		`INSERT OR IGNORE INTO wiki_pages (id, mod_id, entity_type, entity_id, slug, page_type) VALUES (${quote(pageId)}, 'sts2', ${quote(ref.type)}, ${quote(ref.id)}, ${quote(key)}, 'entity');`,
		`INSERT OR IGNORE INTO wiki_sections (id, page_id, section_key, content_type, sort_order) VALUES (${quote(sectionId)}, ${quote(pageId)}, 'document', 'structured', 0);`,
		`INSERT OR IGNORE INTO wiki_revisions (id, section_id, revision_no, content, summary, source_type, source_reference) VALUES (${quote(revisionId)}, ${quote(sectionId)}, 1, ${quote(JSON.stringify(document))}, ${quote(summary)}, 'mod_seed', ${quote(source)});`,
		`UPDATE wiki_sections SET current_revision_id = ${quote(revisionId)}, version = 1 WHERE id = ${quote(sectionId)} AND current_revision_id IS NULL;`,
		''
	)
}

const target = path.join(root, 'migrations/0002_seed_wiki.sql')
fs.writeFileSync(target, lines.join('\n'), 'utf8')
console.log(`Wrote ${documents.length} seed documents to ${target}`)
